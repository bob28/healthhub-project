"""Tests for automatic flagging of measured values on save."""

from decimal import Decimal

import pytest

from apps.directory.models import (
    LabTest,
    ResultFlag,
    TestAnalyte,
    TestCategory,
)
from apps.lab.models import ResultValue, TestOrder, TestResult

pytestmark = pytest.mark.django_db


@pytest.fixture
def result_and_analyte(patient):
    """Return a persisted (TestResult, TestAnalyte) pair to attach values to.

    Builds the full chain — LabTest → analyte, and TestOrder → TestResult —
    so a :class:`~lab.models.ResultValue` can be created against it.

    Args:
        patient: The patient fixture the order belongs to.

    Returns:
        A ``(TestResult, TestAnalyte)`` tuple.
    """
    test = LabTest.objects.create(
        code="CBC", name="Complete Blood Count", category=TestCategory.HEMATOLOGY
    )
    analyte = TestAnalyte.objects.create(
        lab_test=test,
        name="Hemoglobin",
        unit="g/dL",
        ref_low=Decimal("12"),
        ref_high=Decimal("16"),
    )
    order = TestOrder.objects.create(patient=patient, lab_test=test)
    result = TestResult.objects.create(order=order)
    return result, analyte


def test_result_value_autoflags_low(result_and_analyte):
    """A below-range value is flagged LOW without the caller setting it."""
    result, analyte = result_and_analyte
    value = ResultValue.objects.create(
        result=result, analyte=analyte, value=Decimal("10")
    )
    assert value.flag == ResultFlag.LOW


def test_result_value_autoflags_normal(result_and_analyte):
    """An in-range value is flagged NORMAL."""
    result, analyte = result_and_analyte
    value = ResultValue.objects.create(
        result=result, analyte=analyte, value=Decimal("14")
    )
    assert value.flag == ResultFlag.NORMAL


def test_result_value_autoflags_critical_high(result_and_analyte):
    """A far-above-range value escalates to CRITICAL_HIGH."""
    result, analyte = result_and_analyte
    value = ResultValue.objects.create(
        result=result, analyte=analyte, value=Decimal("25")
    )
    assert value.flag == ResultFlag.CRITICAL_HIGH


def test_order_number_autogenerated(patient):
    """Saving a TestOrder without an order number assigns an ``ORD`` code."""
    test = LabTest.objects.create(
        code="LIPID", name="Lipid Panel", category=TestCategory.CHEMISTRY
    )
    order = TestOrder.objects.create(patient=patient, lab_test=test)
    assert order.order_number.startswith("ORD")
    assert len(order.order_number) == 11
